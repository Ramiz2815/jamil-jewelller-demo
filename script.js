/* Fades between the photos inside any  <div class="jewel about-slider">  every 4.5 seconds. */
(function () {
  const INTERVAL = 4500;   // milliseconds (4.5 seconds)
  const reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  document.querySelectorAll('.about-slider').forEach(box => {
    const slides = [...box.querySelectorAll('.slide')];
    if (slides.length < 2) return;
    slides.forEach(s => { s.loading = 'eager'; });          // have the next photo ready before the first swap

    let i = 0, timer = null;
    const dots = document.createElement('div');
    dots.className = 'slider-dots';
    slides.forEach((_, n) => {
      const b = document.createElement('button');
      b.type = 'button';
      b.setAttribute('aria-label', 'Show photo ' + (n + 1));
      b.addEventListener('click', () => { go(n); restart(); });
      dots.appendChild(b);
    });
    box.appendChild(dots);

    function go(n) {
      slides[i].classList.remove('active'); dots.children[i].classList.remove('active');
      i = n;
      slides[i].classList.add('active');    dots.children[i].classList.add('active');
    }
    const next = () => go((i + 1) % slides.length);
    const start = () => { if (!timer && !reduce) timer = setInterval(next, INTERVAL); };
    const stop = () => { clearInterval(timer); timer = null; };
    const restart = () => { stop(); start(); };

    dots.children[0].classList.add('active');
    box.addEventListener('mouseenter', stop);                // pause while the mouse is over it
    box.addEventListener('mouseleave', start);
    document.addEventListener('visibilitychange', () => document.hidden ? stop() : start());
    start();
  });
})();

/* ---------- Image wrapper: correct alt text + lazy loading for every product picture ---------- */
function jewelSvg(seed) {
  let html = jewelSvgRaw(seed);
  const p = products.find(x => x.id === seed);
  if (p) {   // use the real product name as the alt text (the old alt texts were copy-pasted between products)
    html = html.replace(/alt="[^"]*"/, 'alt="' + p.name.replace(/&/g, '&amp;').replace(/"/g, '&quot;') + '"');
  }
  return html.replace('<img ', '<img loading="lazy" decoding="async" ');
}