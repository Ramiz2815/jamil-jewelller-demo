(function () {
  if (!('IntersectionObserver' in window) ||
    window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const io = new IntersectionObserver(entries => {
    entries.forEach(e => { if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); } });
  }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });
  const SEL = '.section-head, .trust-item, .coll-card, #featuredGrid .prod-card, .about > *, .store-grid > *, ' +
    '.contact-grid > *, .reviews-head, .review-note, .term-block, .foot-col';
  function watch() {
    document.querySelectorAll(SEL).forEach(el => {
      if (el.dataset.rv) return;
      el.dataset.rv = '1';
      el.classList.add('reveal');
      el.style.transitionDelay = Math.min([...el.parentNode.children].indexOf(el), 6) * 70 + 'ms';
      io.observe(el);
    });
  }
  watch();
  // cards are re-created when a category filter is clicked
  ['prodGrid', 'featuredGrid', 'collGrid'].forEach(id => {
    const g = document.getElementById(id);
    if (g) new MutationObserver(watch).observe(g, { childList: true });
  });
})();

